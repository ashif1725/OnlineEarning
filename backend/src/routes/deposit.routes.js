"use strict";


/*
|--------------------------------------------------------------------------
| PACKAGES
|--------------------------------------------------------------------------
*/

const express =
    require(
        "express"
    );


const router =
    express.Router();


/*
|--------------------------------------------------------------------------
| DEPOSIT CONTROLLER
|--------------------------------------------------------------------------
*/

const {

    createDepositRequest,

    getUserDepositRequests

} =
    require(
        "../controllers/deposit.controller"
    );


/*
|--------------------------------------------------------------------------
| AUTH MIDDLEWARE
|--------------------------------------------------------------------------
*/

const {

    requireAuth

} =
    require(
        "../middleware/auth.middleware"
    );


/*
|--------------------------------------------------------------------------
| CREATE DEPOSIT REQUEST
|--------------------------------------------------------------------------
|
| POST /api/deposits
|
*/

router.post(

    "/",

    requireAuth,

    createDepositRequest

);


/*
|--------------------------------------------------------------------------
| GET CURRENT USER DEPOSIT REQUESTS
|--------------------------------------------------------------------------
|
| GET /api/deposits
|
*/

router.get(

    "/",

    requireAuth,

    getUserDepositRequests

);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports =
    router;
